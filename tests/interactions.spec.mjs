import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'

const browser = await chromium.launch({ channel: 'chrome', headless: true })
const results = []
const base = process.env.GALLERY_URL || 'http://127.0.0.1:5180'
const settle = page => page.waitForFunction(() => !document.querySelector('[data-transitioning]'))
const trigger = (page, name) => page.getByRole('button', { name, exact: true }).first().evaluate(el => el.click())
const record = (name, detail) => results.push({ name, detail, passed: true })
const errors = []
const open = async (width, reducedMotion = 'no-preference') => {
  const page = await browser.newPage({ viewport: { width, height: width === 390 ? 844 : 900 }, reducedMotion })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(base)
  await page.waitForLoadState('networkidle')
  await page.evaluate(() => document.fonts.ready)
  await page.waitForTimeout(1700)
  return page
}
try {
  for (const width of [1440, 390]) {
    const page = await open(width)
    const seal = await page.locator('.brand-seal').evaluate(el => {
      const style = getComputedStyle(el.querySelector('.seal-characters'))
      return { columns: style.gridTemplateColumns.split(' ').length, rows: style.gridTemplateRows.split(' ').length, glyphs: el.querySelectorAll('.seal-characters > span').length, frame: el.querySelectorAll('.seal-frame path').length }
    })
    assert.deepEqual(seal, { columns: 2, rows: 2, glyphs: 4, frame: 3 })
    assert.match(await page.locator('.hero-actions .button-ink').evaluate(el => getComputedStyle(el, '::before').maskImage), /brush-stroke\.svg/)
    await page.locator('.brand').screenshot({ path: `test-results/logo-${width}.png` })
    record(`Seal and brush ${width}`, 'Four-glyph two-by-two seal, worn double frame, actual brush mask')

    await page.locator('#numbers').scrollIntoViewIfNeeded()
    await page.waitForTimeout(850)
    await trigger(page, '观展簿下一页')
    await page.waitForTimeout(120)
    const ghost = page.locator('.ledger-pages > .transition-ghost')
    assert.equal(await ghost.getAttribute('aria-hidden'), 'true')
    assert.equal(await ghost.evaluate(el => el.inert && !el.id), true)
    const start = await ghost.evaluate(el => getComputedStyle(el).transform)
    await page.waitForTimeout(180)
    const end = await ghost.evaluate(el => getComputedStyle(el).transform)
    assert.notEqual(start, end, 'Page rotation is not moving')
    assert.match(end, /matrix3d/, 'Page turn must include perspective')
    await page.locator('.ledger').screenshot({ path: `test-results/page-turn-${width}.png` })
    await settle(page)
    assert.equal(await page.locator('.ledger-records tbody tr').count(), 6)
    await trigger(page, '观展簿上一页')
    await page.waitForTimeout(70)
    await trigger(page, '观展簿下一页')
    await settle(page)
    assert.equal(await page.locator('.transition-ghost').count(), 0)
    assert.equal(await page.locator('.ledger-records tbody tr').count(), 6)
    await trigger(page, '合上观展簿')
    await page.waitForTimeout(180)
    assert.equal(await page.locator('.ledger > .transition-ghost').count(), 1)
    await settle(page)
    await trigger(page, '打开观展簿')
    await settle(page)
    assert.equal(await page.locator('.ledger-pages').isVisible(), true)
    record(`Book motion ${width}`, 'Perspective changes over time; rapid turns and cover transitions clean up old paper')

    await page.locator('#collection').scrollIntoViewIfNeeded()
    await page.waitForTimeout(850)
    await trigger(page, '展开一水知秋')
    await page.waitForTimeout(120)
    const maskStart = await page.locator('#collection-scroll').evaluate(el => getComputedStyle(el).clipPath)
    await page.waitForTimeout(220)
    const maskEnd = await page.locator('#collection-scroll').evaluate(el => getComputedStyle(el).clipPath)
    assert.notEqual(maskStart, maskEnd)
    await page.locator('.handscroll').screenshot({ path: `test-results/scroll-change-${width}.png` })
    await settle(page)
    const rollerStart = await page.locator('.roller-left').evaluate(el => el.getBoundingClientRect().left)
    await trigger(page, '收起画卷')
    await settle(page)
    const rollerEnd = await page.locator('.roller-left').evaluate(el => el.getBoundingClientRect().left)
    assert.ok(rollerEnd > rollerStart + 60)
    assert.equal(await page.locator('#collection-scroll').evaluate(el => el.inert), true)
    await trigger(page, '展开画卷')
    await settle(page)
    assert.equal(await page.locator('#collection-scroll').evaluate(el => el.inert), false)
    record(`Scroll motion ${width}`, 'Mask unfolds progressively; wooden rollers converge and reopen; hidden content remains inert')

    await page.locator('#scenes').scrollIntoViewIfNeeded()
    await page.waitForTimeout(850)
    await trigger(page, '下一幅画境')
    await page.waitForTimeout(100)
    assert.equal(await page.locator('.scroll-view > .transition-ghost').count(), 1)
    const sceneStart = await page.locator('.scroll-stage:not(.transition-ghost)').evaluate(el => getComputedStyle(el).clipPath)
    await page.waitForTimeout(260)
    assert.notEqual(await page.locator('.scroll-stage:not(.transition-ghost)').evaluate(el => getComputedStyle(el).clipPath), sceneStart)
    await trigger(page, '下一幅画境')
    await page.waitForTimeout(50)
    await trigger(page, '上一幅画境')
    await settle(page)
    assert.equal(await page.locator('.scene-counter').innerText(), '二 / 三')
    assert.equal(await page.locator('.transition-ghost').count(), 0)
    record(`Scene motion ${width}`, 'Old scene retreats, new scene reveals; repeated changes retain correct state')

    await page.locator('.brand').evaluate(el => el.click())
    await page.waitForFunction(() => document.querySelector('[data-navigating="true"]'))
    const position = await page.evaluate(() => scrollY)
    await page.waitForTimeout(240)
    assert.ok(await page.evaluate(() => scrollY) < position)
    await page.evaluate(() => window.dispatchEvent(new WheelEvent('wheel', { deltaY: 100 })))
    assert.equal(await page.locator('[data-navigating]').count(), 0)
    const interrupted = await page.evaluate(() => scrollY)
    await page.waitForTimeout(350)
    assert.ok(Math.abs(await page.evaluate(() => scrollY) - interrupted) < 2, 'Canceled navigation continued')
    if (width === 390) {
      await page.getByRole('button', { name: '打开菜单' }).click()
      await page.locator('#mobile-menu a[href="#journey"]').click()
      assert.equal(await page.locator('#mobile-menu').count(), 0)
    } else await page.locator('.desktop-nav a[href="#journey"]').click()
    await page.waitForFunction(() => !document.querySelector('[data-navigating]') && document.activeElement.id === 'journey')
    const targetTop = await page.locator('#journey').evaluate(el => el.getBoundingClientRect().top)
    assert.ok(targetTop >= 80 && targetTop <= 150)
    assert.equal(await page.evaluate(() => location.hash), '#journey')
    record(`Navigation ${width}`, 'Ink feedback and progressive native scrolling; wheel interrupts; focus and mobile menu work')

    await page.getByRole('button', { name: '观展导览', exact: true }).evaluate(el => el.click())
    await page.waitForTimeout(100)
    assert.ok(await page.locator('dialog').evaluate(el => el.getAnimations().length > 0))
    await page.waitForTimeout(650)
    await page.keyboard.press('Escape')
    await page.waitForTimeout(50)
    assert.ok(await page.locator('dialog').evaluate(el => el.getAnimations().some(animation => animation.playState === 'running')))
    await page.locator('dialog').waitFor({ state: 'hidden' })
    record(`Dialog motion ${width}`, 'Paper unfolds on entry and fades on exit; Escape still returns focus')

    await trigger(page, '下一幅画境')
    await page.waitForTimeout(80)
    await trigger(page, '暂停动态效果')
    await settle(page)
    assert.equal(await page.locator('.transition-ghost').count(), 0)
    assert.equal(await page.locator('.scroll-stage').evaluate(el => getComputedStyle(el).opacity), '1')
    record(`Pause ${width}`, 'Pausing during a scene transition removes snapshots and restores complete content')
    await page.close()
  }
  const page = await open(1440, 'reduce')
  for (const name of ['观展簿下一页', '展开一水知秋', '下一幅画境']) await trigger(page, name)
  assert.equal(await page.locator('.transition-ghost,[data-transitioning]').count(), 0)
  await page.locator('.desktop-nav a[href="#journey"]').evaluate(el => el.click())
  await page.waitForTimeout(100)
  assert.equal(await page.locator('[data-navigating]').count(), 0)
  assert.equal(await page.evaluate(() => document.activeElement.id), 'journey')
  await page.getByRole('button', { name: '观展导览', exact: true }).evaluate(el => el.click())
  assert.equal(await page.locator('dialog').evaluate(el => el.getAnimations().length), 0)
  await page.keyboard.press('Escape')
  await page.locator('dialog').waitFor({ state: 'hidden' })
  record('Reduced motion', 'All paper interactions and navigation work without transition snapshots or dialog animations')
  await page.close()
  assert.deepEqual(errors, [])
  await writeFile('test-results/interactions-report.json', JSON.stringify({ results, errors }, null, 2))
  console.log(JSON.stringify({ passed: results.length, errors }))
} finally { await browser.close() }
