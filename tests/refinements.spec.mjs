import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'

const browser = await chromium.launch({ channel: 'chrome', headless: true })
const base = process.env.GALLERY_URL || 'http://127.0.0.1:5180'
const results = [], errors = []
const record = (name, detail) => results.push({ name, detail, passed: true })
const escape = async page => { await page.keyboard.press('Escape'); await page.locator('dialog').waitFor({ state: 'hidden' }) }
try {
  for (const width of [1920,1440,1366,768,390,375,360]) {
    const page = await browser.newPage({ viewport: { width, height: 844 }, reducedMotion: 'reduce' })
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(base)
    await page.waitForLoadState('networkidle')
    await page.evaluate(() => document.fonts.ready)
    const hero = await page.locator('.hero-caption-text .heading-phrase').evaluateAll(elements => elements.map(el => ({ rectangles: el.getClientRects().length, width: el.getBoundingClientRect().width, parent: el.parentElement.getBoundingClientRect().width })))
    assert.ok(hero.every(item => item.rectangles === 1 && item.width <= item.parent + 1), `Split hero phrase at ${width}`)
    const headings = await page.locator('.section-heading .heading-phrase').evaluateAll(elements => elements.map(el => ({ rectangles: el.getClientRects().length, width: el.getBoundingClientRect().width, parent: el.parentElement.clientWidth })))
    assert.ok(headings.every(item => item.rectangles === 1 && item.width <= item.parent + 1), `Split section heading at ${width}`)
    const controls = await page.locator('.header-tools button:visible').evaluateAll(elements => elements.map(el => { const r=el.getBoundingClientRect(); return { label:el.getAttribute('aria-label'),width:r.width,height:r.height,right:r.right } }))
    assert.ok(controls.every(item => item.width >= 44 && item.height >= 44 && item.right <= width), `Header touch targets at ${width}: ${JSON.stringify(controls)}`)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    assert.equal(await page.locator('.brand-name small').evaluate(el => getComputedStyle(el).fontSize), width <= 600 ? '14px' : '17px')
    assert.equal(await page.locator('.visit-chart svg text').count(), 4, 'Chart repeats visible month labels')
    assert.equal(await page.locator('.chart-access button').count(), 6)
    await page.getByRole('button',{name:'联系与反馈'}).click()
    const phrases = await page.locator('#dialog-title .heading-phrase').evaluateAll(elements => elements.map(el => ({ width:el.getBoundingClientRect().width,parent:el.parentElement.clientWidth })))
    assert.ok(phrases.every(item => item.width <= item.parent), `Split feedback heading at ${width}`)
    await page.getByRole('button',{name:'保存到本机'}).click()
    assert.equal(await page.locator('#feedback').getAttribute('aria-invalid'),'true')
    assert.equal(await page.locator('#feedback').evaluate(el=>getComputedStyle(el).borderColor),'rgb(165, 68, 54)')
    assert.equal(await page.evaluate(()=>document.activeElement.id),'feedback')
    assert.equal(await page.getByRole('dialog').evaluate(el=>el.scrollWidth>el.clientWidth),false)
    const form = page.locator('dialog form')
    const before = await form.evaluate(el=>el.scrollHeight)
    await page.getByLabel('观展感受',{exact:true}).fill('山水之间，静看一卷。')
    assert.equal(await page.locator('#feedback').getAttribute('aria-invalid'),'false')
    assert.equal(await page.locator('#feedback-error').innerText(),'')
    assert.ok(Math.abs(await form.evaluate(el=>el.scrollHeight)-before)<2,'Correction moved the submit control')
    if(width===390||width===1440) await page.screenshot({path:`test-results/refined-form-${width}.png`})
    await escape(page)
    await page.getByRole('button',{name:'我的册页',exact:true}).click()
    assert.equal(await page.locator('.empty-album').count(),1)
    await page.getByRole('dialog').getByRole('link',{name:'去看看册页'}).click()
    assert.equal(await page.getByRole('dialog').count(),0)
    assert.equal(await page.evaluate(()=>location.hash),'#collection')
    record(`Refinements ${width}`,'Semantic phrases, touch targets, one month row, validation focus/border/stable spacing, empty collection entry')
    await page.close()
  }

  for (const deviceScaleFactor of [1,2]) {
    const context = await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor,reducedMotion:'reduce'})
    const optical = await context.newPage()
    await optical.goto(base); await optical.waitForLoadState('networkidle'); await optical.evaluate(()=>document.fonts.ready)
    const seal = optical.locator('.brand-seal')
    assert.equal(await seal.locator('.seal-characters > span').count(),4)
    assert.equal(await seal.evaluate(el=>getComputedStyle(el).transform),'none')
    const geometry = await seal.evaluate(el=>({width:el.clientWidth,height:el.clientHeight,grid:getComputedStyle(el.querySelector('.seal-characters')).gridTemplateColumns,precision:getComputedStyle(el.querySelector('.seal-frame')).shapeRendering}))
    assert.equal(geometry.width,geometry.height)
    assert.equal(geometry.precision,'geometricprecision')
    assert.equal(geometry.grid.split(' ').length,2)
    await seal.screenshot({path:`test-results/refined-seal-dpr-${deviceScaleFactor}.png`})
    record(`Seal pixel density ${deviceScaleFactor}`,'Square frame, four glyphs/two columns, neutral alignment and geometric precision')
    await context.close()
  }

  const slow = await browser.newPage({ viewport:{width:390,height:844},reducedMotion:'reduce' })
  let releaseImage
  const imageGate = new Promise(resolve => { releaseImage = resolve })
  await slow.route('**/assets/scroll-*.webp*',async route => { await imageGate; await route.continue() })
  await slow.goto(base,{waitUntil:'domcontentloaded'})
  await slow.locator('#scenes').scrollIntoViewIfNeeded()
  const loading = slow.locator('.scroll-painting')
  assert.equal(await loading.getAttribute('data-image-state'),'loading')
  assert.match(await loading.locator('.artwork-state').innerText(),/載入中/)
  const loadingBounds = await loading.evaluate(el => ({width:el.clientWidth,height:el.clientHeight}))
  await slow.screenshot({path:'test-results/refined-image-loading.png'})
  releaseImage()
  await slow.waitForFunction(()=>document.querySelector('.scroll-painting')?.dataset.imageState==='loaded')
  assert.deepEqual(await loading.evaluate(el => ({width:el.clientWidth,height:el.clientHeight})),loadingBounds)
  record('Slow image loading','Clear loading state and stable picture dimensions before and after loading')
  await slow.close()

  const page = await browser.newPage({ viewport:{width:390,height:844},reducedMotion:'reduce' })
  await page.addInitScript(()=>localStorage.setItem('shanshui-favorites',JSON.stringify(['mountain'])))
  await page.goto(base); await page.waitForLoadState('networkidle')
  await page.addStyleTag({content:'html { overflow-y: scroll; scrollbar-gutter: stable; } ::-webkit-scrollbar { width: 15px; }'})
  const bounds = await page.locator('.header-tools').evaluate(el=>({right:el.getBoundingClientRect().right,client:document.documentElement.clientWidth}))
  assert.ok(bounds.right <= bounds.client,'Saved badge/header collide with visible scrollbar')
  await page.screenshot({path:'test-results/refined-mobile-scrollbar.png'})
  record('Visible scrollbar','390px layout and saved badge remain inside the usable viewport')

  await page.route('**/assets/scroll-*.webp*',route=>route.abort())
  await page.locator('#scenes').scrollIntoViewIfNeeded()
  await page.waitForFunction(()=>document.querySelector('.scroll-painting')?.dataset.imageState==='error')
  assert.match(await page.locator('.scroll-painting .artwork-state').innerText(),/暫未載入/)
  assert.equal(await page.locator('.scroll-painting').evaluate(el=>getComputedStyle(el).position),'absolute')
  assert.equal(await page.locator('button button').count(),0,'Image fallback added nested buttons')
  await page.screenshot({path:'test-results/refined-image-error.png'})
  await page.unroute('**/assets/scroll-*.webp*')
  await page.evaluate(()=>window.dispatchEvent(new Event('online')))
  await page.waitForFunction(()=>document.querySelector('.scroll-painting')?.dataset.imageState==='loaded')
  assert.equal(await page.locator('.scroll-painting .artwork-state').count(),0)
  record('Image failure/recovery','In-place error label, preserved dimensions and online recovery without nested controls')
  await page.getByRole('button',{name:'查看远岫含烟'}).click()
  assert.equal(await page.locator('.artwork-book').evaluate(el=>getComputedStyle(el).gap),'26px')
  await escape(page)
  await page.context().setOffline(true)
  await page.waitForFunction(()=>document.querySelector('.toast')?.textContent.includes('網絡已斷開'))
  assert.match(await page.locator('.toast').innerText(),/網絡已斷開/)
  await page.context().setOffline(false)
  await page.waitForFunction(()=>document.querySelector('.toast')?.textContent.includes('網絡已恢復'))
  record('Offline feedback','Browser offline/reconnection triggers clear status; loaded gallery remains available')
  await page.close()

  const failure = await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'})
  await failure.addInitScript(()=>{Storage.prototype.setItem=function(){throw new DOMException('Storage unavailable','QuotaExceededError')}})
  await failure.goto(base); await failure.waitForLoadState('networkidle')
  await failure.getByRole('button',{name:'联系与反馈'}).click()
  await failure.getByLabel('观展感受',{exact:true}).fill('这是不能写入存储的反馈。')
  await failure.getByRole('button',{name:'保存到本机'}).click()
  assert.equal(await failure.getByRole('dialog').count(),1)
  assert.match(await failure.locator('#feedback-error').innerText(),/無法保存/)
  assert.equal(await failure.locator('#feedback').getAttribute('aria-invalid'),'false')
  record('Storage failure','Save failure stays visible, never reports success or wrongly marks valid text')
  await failure.close()
  assert.deepEqual(errors,[])
  await writeFile('test-results/refinements-report.json',JSON.stringify({results,errors},null,2))
  console.log(JSON.stringify({passed:results.length,errors}))
} finally {await browser.close()}
